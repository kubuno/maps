// Generates the celestial-body 3D models of the Maps cosmos view as Wavefront OBJ + MTL files, one per body, from
// the body table below. Each body is an equirectangular UV sphere of unit radius (so the renderer scales it by the
// body's radius): the texture wraps longitude → U and latitude → V, north pole at the top of the image — the layout
// every planet texture in `../textures/<body>/` uses. Ringed planets also get a flat annulus (`<body>-ring.obj`).
//
// Pure Node, no dependencies. Run from this folder: `node gen_cosmos_obj.mjs`. The textures themselves are fetched
// separately (see ../README.md); this only writes the geometry (models/) and the materials (materials/) that bind
// each body's textures onto its sphere. Re-running overwrites those files and nothing else.

import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const LON = 96 // longitude segments
const LAT = 48 // latitude segments

// Each body: its sphere, which texture maps it has (color is always present), and an optional ring (inner/outer in
// body radii, from services/worlds.ts). `clouds` is a translucent second map the renderer drapes on a slightly
// larger sphere (same geometry, scaled), so it needs no separate model.
const BODIES = [
  { id: 'sun', bump: false },
  { id: 'mercury', bump: true },
  { id: 'venus', bump: true },
  { id: 'earth', bump: true, bumpExt: 'png', clouds: true },
  { id: 'moon', bump: true },
  { id: 'mars', bump: true },
  { id: 'jupiter', bump: false, ring: { inner: 1.55, outer: 1.85, color: [0.725, 0.663, 0.549], opacity: 0.18 } },
  { id: 'saturn', bump: false, ring: { inner: 1.35, outer: 2.3, texture: true, opacity: 0.9 } },
  { id: 'uranus', bump: false, ring: { inner: 1.5, outer: 1.7, color: [0.624, 0.839, 0.878], opacity: 0.25 } },
  { id: 'neptune', bump: false },
]

// A unit (radius 1) equirectangular UV sphere: positions = normals, texcoords (u = longitude 0→1 eastward, v = 0 at
// the south pole so vt points up to the north pole at the image top). three.js' SphereGeometry winding/orientation.
function sphereObj(id) {
  const pos = []
  const uv = []
  const faces = []
  for (let iy = 0; iy <= LAT; iy++) {
    const v = iy / LAT
    const theta = v * Math.PI
    const sinT = Math.sin(theta)
    const cosT = Math.cos(theta)
    for (let ix = 0; ix <= LON; ix++) {
      const u = ix / LON
      const phi = u * 2 * Math.PI
      const x = -sinT * Math.cos(phi)
      const y = cosT
      const z = sinT * Math.sin(phi)
      pos.push([x, y, z])
      uv.push([u, 1 - v])
    }
  }
  const w = LON + 1
  for (let iy = 0; iy < LAT; iy++) {
    for (let ix = 0; ix < LON; ix++) {
      const a = iy * w + ix + 1 // OBJ is 1-based
      const b = a + w
      const c = a + 1
      const d = b + 1
      if (iy !== 0) faces.push([a, b, c])
      if (iy !== LAT - 1) faces.push([c, b, d])
    }
  }
  return assemble(id, `${id} — unit equirectangular UV sphere (${LON}×${LAT})`, pos, uv, faces, pos)
}

// A flat annulus in the XZ plane (y = 0, normal +Y), inner→outer in body radii. U runs across the ring width
// (inner → outer), V around it — so a 1-D ring-colour strip (saturnringcolor) maps radially.
function ringObj(id, inner, outer) {
  const seg = 160
  const pos = []
  const uv = []
  const faces = []
  for (let i = 0; i <= seg; i++) {
    const a = (i / seg) * 2 * Math.PI
    const ca = Math.cos(a)
    const sa = Math.sin(a)
    pos.push([inner * ca, 0, inner * sa])
    uv.push([0, i / seg])
    pos.push([outer * ca, 0, outer * sa])
    uv.push([1, i / seg])
  }
  for (let i = 0; i < seg; i++) {
    const a = i * 2 + 1 // inner_i
    const b = i * 2 + 2 // outer_i
    const c = i * 2 + 3 // inner_i+1
    const d = i * 2 + 4 // outer_i+1
    faces.push([a, b, c])
    faces.push([c, b, d])
  }
  const n = pos.map(() => [0, 1, 0])
  return assemble(`${id}-ring`, `${id} ring — flat annulus ${inner}–${outer} body radii`, pos, uv, faces, n)
}

function assemble(mtl, title, pos, uv, faces, normals) {
  const L = [`# Kubuno Maps — ${title}`, `# Generated by tools/gen_cosmos_obj.mjs — do not edit by hand.`, `mtllib ${mtl.replace('-ring', '')}.mtl`, '']
  for (const p of pos) L.push(`v ${p.map(fmt).join(' ')}`)
  for (const t of uv) L.push(`vt ${t.map(fmt).join(' ')}`)
  for (const nrm of normals) L.push(`vn ${nrm.map(fmt).join(' ')}`)
  L.push('', `usemtl ${mtl}`, 's 1')
  for (const f of faces) L.push(`f ${f.map((i) => `${i}/${i}/${i}`).join(' ')}`)
  L.push('')
  return L.join('\n')
}

const fmt = (x) => (Math.abs(x) < 1e-7 ? '0' : parseFloat(x.toFixed(6)).toString())

// An MTL binding a body's textures: diffuse colour map, optional bump map, and (for a ringed body) a second material
// for its ring using the ring texture with alpha from the same image's luminance edges handled by the renderer.
function mtl(body) {
  const L = [`# Kubuno Maps — ${body.id} material`, `# Generated by tools/gen_cosmos_obj.mjs — do not edit by hand.`, '']
  L.push(`newmtl ${body.id}`)
  L.push('Ka 1 1 1', 'Kd 1 1 1', 'Ks 0 0 0', 'd 1', 'illum 1')
  L.push(`map_Kd textures/${body.id}/color.jpg`)
  if (body.bump) L.push(`bump -bm 1 textures/${body.id}/bump.${body.bumpExt ?? 'jpg'}`)
  if (body.clouds) {
    L.push('', `newmtl ${body.id}-clouds`, 'Ka 1 1 1', 'Kd 1 1 1', 'd 0.6', 'illum 1', `map_Kd textures/${body.id}/clouds.jpg`)
  }
  if (body.ring) {
    const r = body.ring
    const kd = r.texture ? '1 1 1' : r.color.map(fmt).join(' ')
    L.push('', `newmtl ${body.id}-ring`, 'Ka 1 1 1', `Kd ${kd}`, `d ${fmt(r.opacity)}`, 'illum 1')
    if (r.texture) L.push(`map_Kd textures/${body.id}/ring.jpg`)
  }
  L.push('')
  return L.join('\n')
}

// A texture-neutral shared unit sphere (no material): the geometry every body is — the web 3D scene loads this once
// and reuses it (scaled) for the Sun, the planets and the moons, so the geometry is the same file on web and native.
function plainSphereObj() {
  const s = sphereObj('sphere')
  return s.replace(/^mtllib .*\n/m, '').replace(/^usemtl .*\n/m, '')
}

mkdirSync(join(ROOT, 'models'), { recursive: true })
mkdirSync(join(ROOT, 'materials'), { recursive: true })
writeFileSync(join(ROOT, 'models', 'sphere.obj'), plainSphereObj())
let n = 1
for (const b of BODIES) {
  writeFileSync(join(ROOT, 'models', `${b.id}.obj`), sphereObj(b.id))
  writeFileSync(join(ROOT, 'materials', `${b.id}.mtl`), mtl(b))
  n++
  if (b.ring) {
    writeFileSync(join(ROOT, 'models', `${b.id}-ring.obj`), ringObj(b.id, b.ring.inner, b.ring.outer))
    n++
  }
}
console.log(`wrote ${n} model(s) + ${BODIES.length} material(s) under ${ROOT}`)
